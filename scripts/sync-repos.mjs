// Reads the public repositories of OWNER and writes data/repos.js with the ones tagged with TOPIC.
// Runs in GitHub Actions (see .github/workflows/sync-repos.yml) but can also be run locally: node scripts/sync-repos.mjs
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const OWNER = process.env.OWNER || 'Priyasad010';
const TOPIC = process.env.TOPIC || 'portfolio';
const SELF = process.env.SELF_REPO || 'My_portfolio'; // the portfolio site itself is never listed (its own commits would change the list every run)
const OUT = 'data/repos.js';

/** Keeps public, original (non-fork), non-archived repositories that carry the topic. */
export function selectRepos(all, topic = TOPIC, self = SELF) {
    return all
        .filter(r => !r.fork && !r.archived && !r.private && r.name !== self && (r.topics || []).includes(topic))
        .sort((a, b) => new Date(b.pushed_at) - new Date(a.pushed_at))
        .map(r => ({
            name: r.name,
            description: r.description || '',
            url: r.html_url,
            homepage: r.homepage || '',
            language: r.language || '',
            stars: r.stargazers_count || 0,
            updated: r.pushed_at,
            topics: (r.topics || []).filter(t => t !== topic)
        }));
}

export function render(repos) {
    return '/* Auto-generated by scripts/sync-repos.mjs (GitHub Action "Sync GitHub projects"). Do not edit by hand. */\n' +
        'window.REPOS = ' + JSON.stringify(repos, null, 4) + ';\n';
}

async function main() {
    const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'portfolio-sync' };
    if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

    const res = await fetch(`https://api.github.com/users/${OWNER}/repos?per_page=100&type=owner&sort=pushed`, { headers });
    if (!res.ok) throw new Error(`GitHub API responded ${res.status}`);
    const repos = selectRepos(await res.json());

    const next = render(repos);
    let current = '';
    try { current = await readFile(OUT, 'utf8'); } catch { /* first run */ }
    if (current === next) {
        console.log(`No change (${repos.length} repo(s) tagged "${TOPIC}").`);
        return;
    }
    await mkdir('data', { recursive: true });
    await writeFile(OUT, next);
    console.log(`Updated ${OUT}: ${repos.length} repo(s) tagged "${TOPIC}": ${repos.map(r => r.name).join(', ') || '(none)'}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
    main().catch(e => { console.error(e); process.exit(1); });
}
